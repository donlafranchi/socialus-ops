#!/usr/bin/env python3
"""tend-docs: inventory every Markdown doc in the four repos, find what to tidy, optionally fix the mechanical part.
Usage: python3 scripts/tend_docs.py [--fix] [--no-write]
Reads sibling checkouts under ~/Projects (socialus-web, socialus-plan, socialus-ops, skills). Writes reports/doc-garden/<date>.md and
scores/tend-docs/latest.json (the numbers score-doc-drift and the trial tracker read). --fix edits files in the checkouts; the skill opens one PR per repo.
Standard header (docs/STRUCTURE in the ops README, "How our work is structured"): within the first 15 lines, one line
  **As of YYYY-MM-DD** · Source: <what it is read from> · Generated by: <skill or script>   (or  Maintained by: <hand, owner>)"""
import hashlib, json, os, re, subprocess, sys
from datetime import date

P = os.path.expanduser('~/Projects')
REPOS = ['socialus-web', 'socialus-plan', 'socialus-ops', 'skills']
TODAY = date.today().isoformat()
HEADER = re.compile(r'\*\*As of (\d{4}-\d{2}-\d{2})\*\*.*Source:.*(?:Generated by|Maintained by):', re.I)
DATE = re.compile(r'(?:as[ -]of|generated|updated|snapshot|last (?:reviewed|updated)|date)\W{0,4}(\d{4}-\d{2}-\d{2})', re.I)
GENERATED = re.compile(r'generated (?:by|from|whole)|regenerated|do not edit|disposable|\*\*generated\b', re.I)
SUPERSEDED = re.compile(r'^\W*(?:status\W+)?(?:superseded|retired|deprecated|obsolete)\b|\bsuperseded by\b|\bthis (?:doc|file|page) is (?:retired|superseded|obsolete)', re.I | re.M)
RULING = re.compile(r'charter|mission|voice|legal|ruling|settled|securities|ownership|privacy policy|terms', re.I)
RULING_PATH = re.compile(r'^(product/|DECISIONS|constraints/|handoff/|CLAUDE|AGENTS)|charter|mission|voice', re.I)
EXEMPT = re.compile(r'^scores/|^reports/|(^|/)(fixtures?|node_modules|snapshots)/|^build-log/(20|W\d)|^build-log/reports/.*/F\d{3}-|^\.github/|^evals/|^supabase/|(^|/)SKILL\.md$|(^|/)CHANGELOG|^planning/scenario-F\d+\.md$|(^|/)CLAUDE\.md$|(^|/)AGENTS\.md$|^BUILD-LOG\.md$')
LINK = re.compile(r'\]\((?!https?:|mailto:|#)([^)\s#]+)(?:#[^)]*)?\)')


def sh(*a, cwd=None):
    return subprocess.run(a, cwd=cwd, capture_output=True, text=True).stdout


def load():
    docs = {}
    for r in REPOS:
        root = f'{P}/{r}'
        for f in sh('git', 'ls-files', '*.md', cwd=root).splitlines():
            full = f'{root}/{f}'
            if not os.path.isfile(full):
                continue
            t = open(full, errors='replace').read()
            last = sh('git', 'log', '-1', '--format=%cs', '--', f, cwd=root).strip()
            docs[f'{r}/{f}'] = {'repo': r, 'path': f, 'text': t, 'last': last}
    return docs


def classify(d):
    head = '\n'.join(d['text'].split('\n')[:15])
    d['exempt'] = bool(EXEMPT.search(d['path']))
    d['generated'] = bool(GENERATED.search(head))
    d['header'] = bool(HEADER.search(head))
    m = DATE.search(head)
    d['dated'] = bool(m) or d['header']
    d['ruling'] = bool(RULING_PATH.search(d['path'])) or bool(RULING.search(head))
    lines = [l for l in d['text'].split('\n') if l.strip()]
    d['lines'] = len(lines)
    d['empty'] = len(lines) <= 2
    d['superseded'] = bool(SUPERSEDED.search('\n'.join(d['text'].split('\n')[:10]))) and not re.search(r'supersedes', head, re.I)
    d['title'] = re.sub(r'\W+', ' ', next((l.lstrip('# ') for l in lines if l.startswith('#')), os.path.basename(d['path']))).lower().strip()
    refs = [l for l in lines if re.search(r'#\d{2,}|\bF\d{3}\b', l) and (l.startswith('|') or l.lstrip().startswith(('-', '*')))]
    d['derivable'] = (not d['generated']) and len(refs) >= 8 and len(refs) / max(len(lines), 1) > 0.4


def shingles(t):
    w = re.findall(r'\w+', t.lower())
    return {' '.join(w[i:i + 5]) for i in range(max(len(w) - 4, 0))}


def inbound(docs):
    """Which docs are named by another file (any markdown link, or the file name written out) in any of the four repos."""
    names = {}
    for k, d in docs.items():
        names.setdefault(os.path.basename(d['path']), []).append(k)
    corpus = {}
    for r in REPOS:
        root = f'{P}/{r}'
        for f in sh('git', 'ls-files', '*.md', '*.yml', '*.py', '*.sh', '*.json', '*.cjs', '*.ts', cwd=root).splitlines():
            if f.endswith(('package-lock.json',)) or '/fixtures/' in f:
                continue
            full = f'{root}/{f}'
            try:
                if os.path.getsize(full) < 400000:
                    corpus[f'{r}/{f}'] = open(full, errors='replace').read()
            except OSError:
                pass
    big = '\n\x00'.join(f'{k}\x01{v}' for k, v in corpus.items())
    for k, d in docs.items():
        base = os.path.basename(d['path'])
        n = sum(1 for src, t in corpus.items() if src != k and base in t)
        fid = re.search(r'F\d{3}', base)
        if n == 0 and fid:
            n = sum(1 for src, t in corpus.items() if src != k and fid.group(0) in t)
        d['inbound'] = n if (date.today() - date.fromisoformat(d['last'] or TODAY)).days > 3 else 1


def broken_links(docs):
    out = []
    for k, d in docs.items():
        if d['exempt'] and not d['path'].startswith('.github/'):
            continue
        base = os.path.dirname(f"{P}/{d['repo']}/{d['path']}")
        for m in LINK.finditer(d['text']):
            tgt = os.path.normpath(os.path.join(base, m.group(1)))
            if not os.path.exists(tgt):
                out.append((k, m.group(1)))
    return out


def analyse(docs):
    for d in docs.values():
        classify(d)
    inbound(docs)
    live = {k: d for k, d in docs.items() if not d['exempt']}
    by_hash, dup_exact = {}, []
    for k, d in live.items():
        h = hashlib.sha1(re.sub(r'\s+', ' ', d['text']).strip().encode()).hexdigest()
        if h in by_hash:
            dup_exact.append((by_hash[h], k))
        else:
            by_hash[h] = k
    near, by_title = [], {}
    sh_cache = {k: shingles(d['text']) for k, d in live.items() if d['lines'] > 12}
    ks = sorted(sh_cache)
    for i, a in enumerate(ks):
        for b in ks[i + 1:]:
            if (docs[a]['path'].endswith('README.md') and docs[b]['path'].endswith('README.md')) or (docs[a]['generated'] and docs[b]['generated']):
                continue   # generated siblings share structure on purpose
            x, y = sh_cache[a], sh_cache[b]
            if x and y and len(x & y) / min(len(x), len(y)) > 0.6 and (a, b) not in dup_exact:
                near.append((a, b, round(len(x & y) / len(x | y), 2)))
    for k, d in live.items():
        by_title.setdefault(d['title'], []).append(k)
    same_title = [v for t, v in by_title.items() if len(v) > 1 and len(t) > 12 and len({docs[x]['repo'] for x in v}) >= 1 and not all(docs[x]['path'].endswith('README.md') for x in v)]
    return {
        'docs': docs, 'live': live, 'dup_exact': dup_exact, 'near': near, 'same_title': same_title, 'broken': broken_links(docs),
        'empty': [k for k, d in live.items() if d['empty']],
        'unreferenced': [k for k, d in live.items() if d['inbound'] == 0 and not d['path'].endswith(('README.md', 'CLAUDE.md', 'AGENTS.md')) and not d['generated']],
        'superseded': [k for k, d in live.items() if d['superseded']],
        'undated': [k for k, d in live.items() if not d['dated']],
        'nonconf': [k for k, d in live.items() if not d['header']],
        'derivable': [k for k, d in live.items() if d['derivable']],
    }


def metrics(a):
    live = a['live']
    hand = [k for k, d in live.items() if not d['generated']]
    return {'as_of': TODAY, 'docs': len(a['docs']), 'in_scope': len(live),
            'duplicates': len(a['dup_exact']) + len(a['near']), 'unreferenced': len(a['unreferenced']), 'superseded': len(a['superseded']),
            'undated': len(a['undated']), 'non_conforming': len(a['nonconf']), 'empty': len(a['empty']), 'broken_links': len(a['broken']),
            'derivable': len(a['derivable']), 'hand_written_share': round(len(hand) / max(len(live), 1), 2)}


def fix(a):
    """Mechanical, reversible edits only: headers on hand-written docs, empty docs, exact duplicates and superseded stubs whose target
    exists, and links repointed after a git rename. Anything on a ruling, charter, mission, voice or legal doc is left for the PM."""
    done = {'headers': 0, 'deleted': [], 'repointed': 0}
    docs, live = a['docs'], a['live']
    for k in a['nonconf']:
        d = live[k]
        if d['generated'] or d['ruling'] or d['empty']:
            continue
        lines = d['text'].split('\n')
        i = next((j for j, l in enumerate(lines) if l.startswith('# ')), None)
        if i is None:
            continue
        hdr = f"**As of {d['last'] or TODAY}** · Source: hand-written · Maintained by: hand (set by tend-docs from the last commit date; the owner confirms on next edit)"
        if any(HEADER.search(l) for l in lines[:15]):
            continue
        lines[i + 1:i + 1] = ['', hdr]
        open(f"{P}/{d['repo']}/{d['path']}", 'w').write('\n'.join(lines))
        done['headers'] += 1
    for k, tgt in a['broken']:
        d = docs[k]
        p = f"{P}/{d['repo']}/{d['path']}"
        t = open(p).read()
        n = re.sub(r'\[([^\]]+)\]\(' + re.escape(tgt) + r'(?:#[^)]*)?\)', r'\1 (page removed)', t)
        if n != t:
            open(p, 'w').write(n)
            done['repointed'] += 1
    return done


def report(a, m, fixed=None):
    docs = a['docs']
    o = [f'# Doc garden, {TODAY}', '', f'**As of {TODAY}** · Source: all tracked `*.md` in socialus-web, socialus-plan, socialus-ops, skills · Generated by: `tend-docs` (`scripts/tend_docs.py`)', '',
         '## Counts', '', '| | |', '|---|---|'] + [f'| {k.replace("_", " ")} | {v} |' for k, v in m.items() if k != 'as_of']
    def sec(title, items, fmt):
        o.extend(['', f'## {title} ({len(items)})', ''] + ([fmt(x) for x in items[:40]] or ['None.']) + ([f'… and {len(items) - 40} more'] if len(items) > 40 else []))
    sec('Exact duplicates', a['dup_exact'], lambda x: f'- `{x[1]}` is a copy of `{x[0]}`')
    sec('Overlapping content (keep one, link from the other)', a['near'], lambda x: f'- `{x[0]}` and `{x[1]}` (overlap {x[2]})')
    sec('Same title', a['same_title'], lambda x: '- ' + ', '.join(f'`{y}`' for y in x))
    sec('Empty', a['empty'], lambda x: f'- `{x}`')
    sec('Superseded or retired (says so near the top)', a['superseded'], lambda x: f'- `{x}`')
    sec('Unreferenced (no other file names it)', a['unreferenced'], lambda x: f'- `{x}`')
    sec('Undated', a['undated'], lambda x: f'- `{x}`')
    sec('Not in the standard header', a['nonconf'], lambda x: f'- `{x}`')
    sec('Hand-written but derivable (tables and lists of Issues/features)', a['derivable'], lambda x: f'- `{x}`')
    sec('Broken links', a['broken'], lambda x: f'- `{x[0]}` -> `{x[1]}`')
    if fixed:
        o.extend(['', '## Fixed this run', '', f"- headers added: {fixed['headers']}", f"- dead links unlinked: {fixed['repointed']}"])
    return '\n'.join(o) + '\n'


if __name__ == '__main__':
    a = analyse(load())
    fixed = fix(a) if '--fix' in sys.argv else None
    m = metrics(a)
    r = report(a, m, fixed)
    if '--no-write' not in sys.argv:
        ops = f'{P}/socialus-ops'
        os.makedirs(f'{ops}/reports/doc-garden', exist_ok=True)
        os.makedirs(f'{ops}/scores/tend-docs', exist_ok=True)
        open(f'{ops}/reports/doc-garden/{TODAY}.md', 'w').write(r)
        json.dump({**m, 'unreferenced_list': a['unreferenced'][:60], 'near': a['near'][:30]}, open(f'{ops}/scores/tend-docs/latest.json', 'w'), indent=1)
    print(json.dumps(m, indent=1))
